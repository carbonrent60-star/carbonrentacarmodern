type LogoPair = {
  light: LogoComponent;
  dark: LogoComponent;
};

function normalizeBrand(brand?: string | null) {
  return (brand ?? "")
    .normalize("NFKD")
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "");
}

