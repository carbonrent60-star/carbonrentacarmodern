export function CarBrandLogo({
  brand,
  size = 28,
  tone = "light",
}: {
  brand?: string | null;
  size?: number;
  tone?: "light" | "dark";
}) {
  const canonical = brandAliases[normalizeBrand(brand)];
  const logo = canonical ? brandLogos[canonical] : null;
  const Logo = logo?.[tone] ?? logo?.light;

  if (Logo) {
    return <Logo width={size} height={size} aria-label={`${canonical} loqosu`} />;
  }

  return <strong aria-label={`${brand ?? "Brend"} loqosu`}>{(brand ?? "C").slice(0, 2).toUpperCase()}</strong>;
}
